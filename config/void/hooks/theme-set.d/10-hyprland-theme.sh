#!/bin/bash
set -euo pipefail

CURRENT_THEME="$HOME/.local/state/void/current/theme"
THEME_CONF="$HOME/.config/hypr/conf/theme.conf"

if [[ ! -d "$CURRENT_THEME" ]]; then
  exit 0
fi

COLORS_TOML="$CURRENT_THEME/colors.toml"
HYPR_LUA="$CURRENT_THEME/hyprland.lua"

# Fallback defaults
accent="7aa2f7"
bg="1a1b26"
fg="c0caf5"
muted="292e42"
urgent="f7768e"

if [[ -f "$COLORS_TOML" ]]; then
  val=$(grep -E '^[[:space:]]*accent[[:space:]]*=' "$COLORS_TOML" | head -n1 | sed -E 's/.*"#(.*)".*/\1/')
  [[ -n "$val" ]] && accent="$val"
  val=$(grep -E '^[[:space:]]*background[[:space:]]*=' "$COLORS_TOML" | head -n1 | sed -E 's/.*"#(.*)".*/\1/')
  [[ -n "$val" ]] && bg="$val"
  val=$(grep -E '^[[:space:]]*foreground[[:space:]]*=' "$COLORS_TOML" | head -n1 | sed -E 's/.*"#(.*)".*/\1/')
  [[ -n "$val" ]] && fg="$val"
  val=$(grep -E '^[[:space:]]*muted[[:space:]]*=' "$COLORS_TOML" | head -n1 | sed -E 's/.*"#(.*)".*/\1/')
  [[ -n "$val" ]] && muted="$val"
  val=$(grep -E '^[[:space:]]*red[[:space:]]*=' "$COLORS_TOML" | head -n1 | sed -E 's/.*"#(.*)".*/\1/')
  [[ -n "$val" ]] && urgent="$val"
fi

active_border="rgba(${accent}ee)"
inactive_border="rgba(595959aa)"

if [[ -f "$HYPR_LUA" ]]; then
  if grep -q "local active_border_color" "$HYPR_LUA"; then
    lua_active=$(grep "local active_border_color" "$HYPR_LUA" | head -n1)
    if [[ "$lua_active" =~ \{[[:space:]]*colors[[:space:]]*=[[:space:]]*\{([^}]+)\}(,[[:space:]]*angle[[:space:]]*=[[:space:]]*([0-9]+))? ]]; then
      colors_raw="${BASH_REMATCH[1]}"
      angle="${BASH_REMATCH[3]:-45}"
      clean_colors=$(echo "$colors_raw" | sed -E 's/["'\'']//g; s/,/ /g' | xargs)
      active_border="$clean_colors ${angle}deg"
    elif [[ "$lua_active" =~ \"([^\"]+)\" ]]; then
      raw_val="${BASH_REMATCH[1]}"
      if [[ "$raw_val" == \#* ]]; then
        active_border="rgba(${raw_val#\#}ee)"
      else
        active_border="$raw_val"
      fi
    fi
  fi

  if grep -q "local inactive_border_color" "$HYPR_LUA"; then
    lua_inactive=$(grep "local inactive_border_color" "$HYPR_LUA" | head -n1)
    if [[ "$lua_inactive" =~ \"([^\"]+)\" ]]; then
      raw_val="${BASH_REMATCH[1]}"
      if [[ "$raw_val" == \#* ]]; then
        inactive_border="rgba(${raw_val#\#}aa)"
      else
        inactive_border="$raw_val"
      fi
    fi
  fi
fi

mkdir -p "$(dirname "$THEME_CONF")"
cat << CONF > "$THEME_CONF"
# Autogenerated by Omarchy theme synchronization hook
\$theme_bg = rgb($bg)
\$theme_surface = rgb($muted)
\$theme_fg = rgb($fg)
\$theme_accent = rgb($accent)
\$theme_urgent = rgb($urgent)
\$active_border = $active_border
\$inactive_border = $inactive_border
CONF

# Also update dotfiles repo copy if exists
DOTFILES_CONF="$HOME/quattro-void-dotfiles/config/hypr/conf/theme.conf"
if [[ -d "$(dirname "$DOTFILES_CONF")" ]]; then
  cp "$THEME_CONF" "$DOTFILES_CONF"
fi

# Reload hyprland live if running
hyprctl reload >/dev/null 2>&1 || true
